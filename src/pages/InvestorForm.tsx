import React, { useState } from 'react'
import { ArrowLeft, Save, UserRound } from 'lucide-react'
import { Investor } from '../types'
import { PageHeader } from '../shared'
import { api } from '../api/client'

type ApiRecord = Record<string, unknown>
const s = (v: unknown) => v == null ? '' : String(v)
function toInvestor(r: ApiRecord): Investor {
  const id = s(r.InvesterID ?? r.id)
  return {
    id, name: s(r.Name ?? r.name), type: s(r.TypeName ?? r.Type ?? r.type ?? 'Owner'),
    address1: s(r.AddressLine1 ?? r.address1), address2: s(r.AddressLine2 ?? r.address2),
    city: s(r.City ?? r.city), phone: s(r.ContactNo ?? r.phone),
    buildings: Number(r.Buildings ?? r.buildings ?? 0), status: s(r.Status ?? r.status ?? 'Active')
  }
}
export function InvestorForm({ value, onBack, onSave }: { value?: string; onBack: () => void; onSave: () => void }) {
  const editing = Boolean(value)
  const [form, setForm] = useState<Investor>({ id: value || '', name: '', type: 'Owner', address1: '', address2: '', city: '', phone: '', buildings: 0, status: 'Active' })
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState('')
  const set = (key: keyof Investor, value: string | number) => setForm(prev => ({ ...prev, [key]: value }))
  const submit = async (e: React.FormEvent) => {
    e.preventDefault(); setSaving(true); setError('')
    const payload = {
      Name: form.name.trim(), TypeName: form.type, Type: form.type,
      AddressLine1: form.address1, AddressLine2: form.address2, City: form.city,
      ContactNo: form.phone, IsOwner: form.type.toLowerCase().includes('owner') ? 1 : 0,
      IsInvestor: form.type.toLowerCase().includes('investor') ? 1 : 0
    }
    try {
      const result = editing
        ? await api.update<{data?: ApiRecord}>('investors', form.id, payload)
        : await api.create<{data?: ApiRecord}>('investors', payload)
      const saved = result?.data ? toInvestor(result.data) : form
      onSave(saved);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Unable to save investor. Check the API and database fields.')
    } finally { setSaving(false) }
  }
  return <div className="page-stack">
    <PageHeader title={editing ? 'Edit Investor / Owner' : 'Create Investor / Owner'} subtitle={editing ? `Update ${value?.name || 'investor'} details.` : 'Create a new property owner or investor.'} action={<button className="secondary-btn" onClick={onBack}><ArrowLeft size={16}/> Back</button>}/>
    <form className="form-stack" onSubmit={submit}>
      <section className="form-card">
        <div className="form-card-head"><span><UserRound size={17}/></span><div><h2>Investor / Owner Details</h2><p>Basic contact and portfolio information.</p></div></div>
        <div className="form-grid three">
          <label className="field-wrap"><span>Investor ID</span><input value={form.id} onChange={e => set('id', e.target.value)} placeholder="Generated by database" disabled={editing}/></label>
          <label className="field-wrap"><span><em>*</em>Name</span><input required value={form.name} onChange={e => set('name', e.target.value)} placeholder="Name"/></label>
          <label className="field-wrap"><span>Type</span><select value={form.type} onChange={e => set('type', e.target.value)}><option>Investor, Owner</option><option>Investor</option><option>Owner</option></select></label>
          <label className="field-wrap"><span>Phone</span><input value={form.phone} onChange={e => set('phone', e.target.value)} placeholder="+974 5550 1122"/></label>
          <label className="field-wrap"><span>City</span><input value={form.city} onChange={e => set('city', e.target.value)} placeholder="Doha"/></label>
          <label className="field-wrap"><span>Status</span><select value={form.status} onChange={e => set('status', e.target.value)}><option>Active</option><option>Inactive</option></select></label>
          <label className="field-wrap"><span>Address Line 1</span><input value={form.address1} onChange={e => set('address1', e.target.value)} placeholder="Street / building address"/></label>
          <label className="field-wrap"><span>Address Line 2</span><input value={form.address2} onChange={e => set('address2', e.target.value)} placeholder="Apartment / area / additional address"/></label>
          <label className="field-wrap"><span>Properties</span><input type="number" min="0" value={form.buildings} onChange={e => set('buildings', Number(e.target.value) || 0)} disabled/></label>
        </div>
      </section>
      {error && <p role="alert" className="error-text">{error}</p>}
      <div className="inline-actions bottom-actions"><button type="button" className="secondary-btn" onClick={onBack} disabled={saving}>Cancel</button><button type="submit" className="primary-btn" disabled={saving}><Save size={16}/> {saving ? 'Saving…' : editing ? 'Save changes' : 'Create investor'}</button></div>
    </form>
  </div>
}
export default InvestorForm
